// Generates src/styles/tokens.css from a snapshot of the Simario.pen variables.
//
// Refresh the snapshot through the Pencil MCP (`Print(JSON.stringify(GetVariables()))`),
// save it as scripts/pencil-variables.json, then run `npm run tokens`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, 'pencil-variables.json');
const target = resolve(here, '../src/styles/tokens.css');

const FONT_STACKS = {
  'font-display': `'Newsreader Variable', 'Newsreader', 'Iowan Old Style', Georgia, serif`,
  'font-sans': `'Plus Jakarta Sans Variable', 'Plus Jakarta Sans', 'Segoe UI', system-ui, sans-serif`,
  'font-mono': `'JetBrains Mono Variable', 'JetBrains Mono', ui-monospace, Menlo, monospace`,
};

// Numbers that are not lengths in CSS.
const UNITLESS = new Set(['breakpoint', 'frame-desktop-w', 'frame-desktop-h', 'frame-mobile-w']);

const { variables } = JSON.parse(readFileSync(source, 'utf8'));
const light = [];
const dark = [];

const valueFor = (def, mode) => {
  if (!Array.isArray(def.value)) return def.value;
  const entry = def.value.find((v) => v.theme?.mode === mode) ?? def.value[0];
  return entry.value;
};

for (const [name, def] of Object.entries(variables).sort(([a], [b]) => a.localeCompare(b))) {
  if (def.type === 'string') {
    light.push(`  --${name}: ${FONT_STACKS[name] ?? `'${def.value}'`};`);
    continue;
  }
  if (def.type === 'number') {
    light.push(`  --${name}: ${UNITLESS.has(name) ? def.value : `${def.value}px`};`);
    continue;
  }
  const l = valueFor(def, 'light');
  const d = valueFor(def, 'dark');
  light.push(`  --${name}: ${l};`);
  if (Array.isArray(def.value) && d !== l) dark.push(`  --${name}: ${d};`);
}

// Composite shadows (design system §4) built from the themed shadow colour tokens.
const shadows = [
  '  --shadow-xs: 0 1px 2px var(--shadow-xs-color);',
  '  --shadow-card: 0 1px 2px var(--shadow-card-1), 0 8px 24px -8px var(--shadow-card-2);',
  '  --shadow-card-hover: 0 2px 4px var(--shadow-card-hover-1), 0 22px 44px -14px var(--shadow-card-hover-2);',
  '  --shadow-md: 0 2px 4px var(--shadow-md-1), 0 8px 20px var(--shadow-md-2);',
  '  --shadow-lg: 0 4px 8px var(--shadow-lg-1), 0 18px 40px var(--shadow-lg-2);',
];
// `shadow-xs` is a colour in the .pen file; expose it under a non-clashing name.
const rename = (line) => line.replace('--shadow-xs:', '--shadow-xs-color:');

const css = `/* Generated by scripts/build-tokens.mjs from scripts/pencil-variables.json — do not edit by hand. */
:root {
  color-scheme: light;
${light.map(rename).join('\n')}

${shadows.join('\n')}
}

[data-theme='dark'] {
  color-scheme: dark;
${dark.map(rename).join('\n')}
}
`;

writeFileSync(target, css);
console.log(`tokens.css: ${light.length} tokens, ${dark.length} dark overrides`);
