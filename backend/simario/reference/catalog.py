"""Production reference data (spec §4.6): system constants derived from the prototype export
(catalog.json, regenerated by `manage.py build_catalog`) plus stages, templates and score
options read straight from docs/seed. Template text is never copied into code (CLAUDE.md §5)."""

import json
from pathlib import Path
from typing import Any

from django.apps import apps
from django.db import transaction

from simario.devtools.seed import convert_row, known_ids, legacy_uuid

CATALOG_PATH = Path(__file__).resolve().parent / "catalog.json"
REPO_DIR = Path(__file__).resolve().parents[3]
RAPIM_PATH = REPO_DIR / "docs" / "seed" / "template_risiko_rapim.json"
OPTIONS_PATH = REPO_DIR / "docs" / "seed" / "pilihan_penilaian.json"

BUILTIN_ROLE_CODES = {"SAD", "PMR", "PMT", "PJM", "PMD"}
TYPE_ID = {"KPA": "pt-kpa", "PPK": "pt-ppk", "POKJA": "pt-pokja", "PJP": "pt-pjp"}
ACTIVE_BAND_VERSION = "sbv-1"
TEMPLATES_UPDATED = "2026-10-12"


def build_catalog(demo: dict[str, Any]) -> dict[str, Any]:
    """Base reference from the export, without demo-only changes (custom roles, later form
    and band versions)."""
    db = demo["db"]
    roles = [r for r in db["roles"] if r["code"] in BUILTIN_ROLE_CODES]
    role_ids = {r["id"] for r in roles}
    return {
        "permissions": demo["permissions"],
        "roles": roles,
        "rolePermissions": [rp for rp in db["rolePermissions"] if rp["roleId"] in role_ids],
        "positionTypes": db["positionTypes"],
        "dataUmumForms": [{**f, "active": True} for f in db["dataUmumForms"] if f["version"] == 1],
        "scoreBandVersions": [
            {**v, "status": "active"}
            for v in db["scoreBandVersions"]
            if v["id"] == ACTIVE_BAND_VERSION
        ],
        "scoreBands": [b for b in db["scoreBands"] if b["versionId"] == ACTIVE_BAND_VERSION],
    }


def _rapim_rows() -> dict[str, list[dict[str, Any]]]:
    rapim = json.loads(RAPIM_PATH.read_text(encoding="utf-8"))
    stages, templates, mitigations = [], [], []
    for ptype in rapim["positionTypes"]:
        type_id = TYPE_ID[ptype["code"]]
        for stage in ptype["stages"]:
            stage_id = f"stg-{stage['code']}"
            stages.append(
                {
                    "id": stage_id,
                    "positionTypeId": type_id,
                    "name": stage["name"],
                    "order": stage["order"],
                    "active": True,
                }
            )
            for tpl in stage["templates"]:
                tpl_id = f"tpl-{tpl['code']}"
                templates.append(
                    {
                        "id": tpl_id,
                        "code": tpl["code"],
                        "positionTypeId": type_id,
                        "stageId": stage_id,
                        "riskType": tpl["riskType"],
                        "description": tpl["description"],
                        "order": tpl["order"],
                        "active": True,
                        "updatedAt": TEMPLATES_UPDATED,
                    }
                )
                for m in tpl["mitigations"]:
                    mitigations.append(
                        {
                            "id": f"mtpl-{m['code']}",
                            "code": m["code"],
                            "riskTemplateId": tpl_id,
                            "description": m["description"],
                            "order": m["order"],
                            "active": True,
                        }
                    )
    return {"stages": stages, "riskTemplates": templates, "mitigationTemplates": mitigations}


def _option_rows() -> list[dict[str, Any]]:
    options = json.loads(OPTIONS_PATH.read_text(encoding="utf-8"))["options"]
    rows = []
    for order, opt in enumerate(sorted(options, key=lambda o: o["value"]), start=1):
        value = opt["value"]
        key = int(value) if float(value).is_integer() else value
        rows.append(
            {
                "id": f"so-{ACTIVE_BAND_VERSION}-{key}",
                "versionId": ACTIVE_BAND_VERSION,
                "value": value,
                "label": opt["label"],
                "order": order,
            }
        )
    return rows


MODELS = [
    ("roles", "org.Role"),
    ("positionTypes", "org.PositionType"),
    ("scoreBandVersions", "reference.ScoreBandVersion"),
    ("dataUmumForms", "reference.DataUmumForm"),
    ("stages", "reference.Stage"),
    ("riskTemplates", "reference.RiskTemplate"),
    ("mitigationTemplates", "reference.MitigationTemplate"),
    ("scoreOptions", "reference.ScoreOption"),
]


@transaction.atomic
def seed_reference() -> dict[str, int]:
    """Creates missing reference rows; never overwrites existing ones. Returns rows created."""
    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    data = {**catalog, **_rapim_rows(), "scoreOptions": _option_rows()}
    known = known_ids(data)
    created: dict[str, int] = {}

    permission = apps.get_model("org.Permission")
    created["permissions"] = sum(
        permission.objects.get_or_create(
            code=p["code"],
            defaults={k: v for k, v in convert_row("p", p, known).items() if k != "code"},
        )[1]
        for p in data["permissions"]
    )
    for collection, label in MODELS:
        model = apps.get_model(label)
        n = 0
        for raw in data[collection]:
            row = convert_row(collection, raw, known)
            if collection == "stages":
                row["code"] = raw["id"].removeprefix("stg-")
            pk = row.pop("id")
            n += model.objects.get_or_create(id=pk, defaults=row)[1]
        created[collection] = n

    role_permission = apps.get_model("org.RolePermission")
    created["rolePermissions"] = sum(
        role_permission.objects.get_or_create(
            role_id=legacy_uuid(rp["roleId"]),
            permission_id=rp["permission"],
            defaults={"scope": rp["scope"]},
        )[1]
        for rp in data["rolePermissions"]
    )
    band = apps.get_model("reference.ScoreBand")
    version = legacy_uuid(ACTIVE_BAND_VERSION)
    created["scoreBands"] = 0
    if not band.objects.filter(version_id=version).exists():
        for b in data["scoreBands"]:
            band.objects.create(**convert_row("scoreBands", b, known))
        created["scoreBands"] = len(data["scoreBands"])
    return created
